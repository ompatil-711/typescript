// Basic TypeScript example

let message: string = "Hello, TypeScript!";
let count: number = 10;
let isReady: boolean = true;


function greet(name: string): string {
  return `Hello, ${name}!`;
}

console.log(message);
console.log(greet("Alice"));
console.log(`Count: ${count}`);
console.log(`Is ready: ${isReady}`);
